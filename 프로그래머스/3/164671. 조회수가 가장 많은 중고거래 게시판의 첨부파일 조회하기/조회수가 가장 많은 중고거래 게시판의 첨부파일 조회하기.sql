SELECT CONCAT('/home/grep/src/', UGF.BOARD_ID, '/', UGF.FILE_ID, UGF.FILE_NAME, UGF.FILE_EXT) FILE_PATH
FROM USED_GOODS_BOARD UGB JOIN USED_GOODS_FILE UGF ON UGB.BOARD_ID = UGF.BOARD_ID
WHERE UGB.BOARD_ID = (SELECT BOARD_ID 
FROM USED_GOODS_BOARD
WHERE VIEWS = (SELECT MAX(VIEWS)
              FROM USED_GOODS_BOARD))
ORDER BY FILE_ID DESC